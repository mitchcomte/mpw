create policy "public active vendors"
on vendor_profiles for select using (status='active');

create policy "vendors manage own profile"
on vendor_profiles for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

create policy "public approved reviews"
on reviews for select using (status='approved');

create policy "users manage own favorites"
on favorites for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
